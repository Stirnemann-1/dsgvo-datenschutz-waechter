// DSGVO Datenschutz Wächter – Menüleisten-App
//
// Überwacht die Zwischenablage. Sobald Text kopiert wird (⌘C), werden Namen,
// E-Mail-Adressen, Telefonnummern, IBAN, AHV-Nummern, Adressen usw. durch
// nummerierte Platzhalter ersetzt. Mit ⌃⌥V wird kopierter Text mit
// Platzhaltern wieder mit den Originalen eingefügt.
//
// Alles läuft lokal. Die Zuordnung liegt nur im Arbeitsspeicher; Protokoll
// und Mitteilungen enthalten nie Originalwerte.

import AppKit
import DatenschutzKern

final class Waechter: NSObject {
    static let ordner = FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Application Support/Datenschutz-Waechter", isDirectory: true)
    static let datei = ordner.appendingPathComponent("einstellungen.json")

    /// Inhalte mit diesen Typen werden nie verändert
    static let ueberspringen: Set<String> = [
        "org.nspasteboard.ConcealedType", // Passwortmanager
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "public.file-url", // im Finder kopierte Dateien
        "NSFilenamesPboardType",
    ]

    private let statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
    private let pb = NSPasteboard.general
    private let eigenePID = ProcessInfo.processInfo.processIdentifier
    private let appleErkenner = AppleNamenErkenner()
    private let tastenkuerzel = Tastenkuerzel()
    private let mitteilungen = Mitteilungen()

    private var einstellungen = Einstellungen()
    private var anonymisierer = Anonymisierer()
    private var letzterStand = 0
    private var eigenerStand = -1
    private var letztesOriginal: String?
    private var aktiv = true
    private var symbolZuruecksetzenUm: Date?
    private var kuerzelAnzeige = ""
    private var platzhalterText: String?
    private var einfuegenFrist = Date()
    private var bedienungshilfenGefragt = false

    private var mAktiv = NSMenuItem()
    private var mStatus = NSMenuItem()
    private var mWarnung = NSMenuItem()
    private var mEinfuegen = NSMenuItem()
    private var mMitteilungen = NSMenuItem()

    // MARK: Start

    func starten() {
        einstellungen = einstellungenLaden()
        anonymisierer = Anonymisierer(einstellungen: einstellungen, namenserkenner: namenserkenner())
        letzterStand = pb.changeCount
        menueBauen()
        symbolSetzen()
        mitteilungen.vorbereiten()
        tastenkuerzelEinrichten()

        let timer = Timer(timeInterval: 0.25, target: self, selector: #selector(pruefen), userInfo: nil, repeats: true)
        RunLoop.main.add(timer, forMode: .common)
        log("gestartet (Apple-Namenserkennung \(einstellungen.namenserkennungApple ? "an" : "aus"))")
    }

    private func menueBauen() {
        let menu = NSMenu()
        menu.autoenablesItems = false

        func eintrag(_ titel: String, _ aktion: Selector?) -> NSMenuItem {
            let m = NSMenuItem(title: titel, action: aktion, keyEquivalent: "")
            m.target = self
            m.isEnabled = aktion != nil
            menu.addItem(m)
            return m
        }

        mAktiv = eintrag("DSGVO Datenschutz aktiv", #selector(umschalten))
        mAktiv.state = .on
        mStatus = eintrag("Noch nichts geprüft", nil)
        mWarnung = eintrag(" ", nil)
        mWarnung.isHidden = true
        menu.addItem(.separator())
        mEinfuegen = eintrag("Mit Originalen einfügen", #selector(mitOriginalenEinfuegenMenue))
        _ = eintrag("Platzhalter in Zwischenablage zurückübersetzen", #selector(zurueckuebersetzen))
        _ = eintrag("Original der letzten Kopie zurück in die Zwischenablage", #selector(originalZurueck))
        menu.addItem(.separator())
        _ = eintrag("Zuordnungstabelle anzeigen …", #selector(tabelleZeigen))
        _ = eintrag("Zuordnungen löschen", #selector(zuordnungenLoeschen))
        menu.addItem(.separator())
        mMitteilungen = eintrag("Mitteilungen anzeigen", #selector(mitteilungenUmschalten))
        mMitteilungen.state = einstellungen.benachrichtigungen ? .on : .off
        _ = eintrag("Einstellungen öffnen …", #selector(einstellungenOeffnen))
        _ = eintrag("Einstellungen neu laden", #selector(einstellungenNeuLaden))
        menu.addItem(.separator())
        let beenden = NSMenuItem(title: "Beenden", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        beenden.target = NSApp
        menu.addItem(beenden)

        statusItem.menu = menu
    }

    private func symbolSetzen(zahl: Int? = nil) {
        guard let knopf = statusItem.button else { return }
        let zusatz = zahl.map { " \($0)" } ?? ""
        let name = aktiv ? "lock.shield" : "shield.slash"
        if let bild = NSImage(systemSymbolName: name, accessibilityDescription: "DSGVO Datenschutz Wächter") {
            bild.isTemplate = true
            knopf.image = bild
            knopf.imagePosition = .imageLeading
            knopf.title = zusatz
        } else {
            knopf.image = nil
            knopf.title = (aktiv ? "🛡" : "⏸") + zusatz
        }
    }

    // MARK: Einstellungen

    private func einstellungenLaden() -> Einstellungen {
        let fm = FileManager.default
        try? fm.createDirectory(at: Waechter.ordner, withIntermediateDirectories: true)
        if !fm.fileExists(atPath: Waechter.datei.path),
           let vorlage = Bundle.main.url(forResource: "einstellungen", withExtension: "json") {
            try? fm.copyItem(at: vorlage, to: Waechter.datei)
        }
        do {
            return try Einstellungen.laden(von: Waechter.datei)
        } catch {
            if fm.fileExists(atPath: Waechter.datei.path) {
                log("Einstellungen fehlerhaft: \(error.localizedDescription)")
                mitteilungen.senden(titel: "Einstellungen fehlerhaft", text: "Standardwerte werden verwendet.")
            }
            return Einstellungen()
        }
    }

    private func namenserkenner() -> [Namenserkenner] {
        guard einstellungen.namenserkennungApple else { return [] }
        let erkenner = appleErkenner
        return [{ text in erkenner.erkennen(text) }]
    }

    private func tastenkuerzelEinrichten() {
        tastenkuerzel.entfernen()
        kuerzelAnzeige = ""
        let kuerzel = einstellungen.tastenkuerzel.trimmingCharacters(in: .whitespaces)
        if !kuerzel.isEmpty {
            do {
                let k = try KuerzelLeser.lesen(kuerzel)
                tastenkuerzel.aktion = { [weak self] in self?.mitOriginalenEinfuegen() }
                try tastenkuerzel.registrieren(code: k.code, modifier: k.modifier)
                kuerzelAnzeige = k.anzeige
                log("Tastenkürzel \(k.anzeige) aktiv")
            } catch {
                log("Tastenkürzel nicht verfügbar: \(error.localizedDescription)")
                melden("Tastenkürzel nicht verfügbar", error.localizedDescription, immer: true)
            }
        }
        mEinfuegen.title = "Mit Originalen einfügen" + (kuerzelAnzeige.isEmpty ? "" : "   \(kuerzelAnzeige)")
    }

    // MARK: Hilfen

    private func melden(_ titel: String, _ text: String, immer: Bool = false) {
        guard immer || einstellungen.benachrichtigungen else { return }
        mitteilungen.senden(titel: titel, text: text)
    }

    private func schreiben(_ text: String, vertraulich: Bool = false) {
        pb.clearContents()
        pb.setString(text, forType: .string)
        if vertraulich {
            // Zwischenablage-Verläufe (Spotlight, Maccy, Paste …) sollen Originale nicht speichern
            for typ in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType"] {
                pb.setData(Data(), forType: NSPasteboard.PasteboardType(typ))
            }
        }
        eigenerStand = pb.changeCount
        letzterStand = eigenerStand
    }

    private func warnungSetzen(_ text: String?) {
        mWarnung.title = text ?? " "
        mWarnung.isHidden = (text == nil)
    }

    private func nachVorne() {
        NSApp.activate(ignoringOtherApps: true)
    }

    private static func uhrzeit() -> String {
        let f = DateFormatter()
        f.dateFormat = "HH:mm"
        return f.string(from: Date())
    }

    // MARK: Kern: neue Kopie prüfen

    @objc private func pruefen() {
        if let um = symbolZuruecksetzenUm, Date() > um {
            symbolZuruecksetzenUm = nil
            symbolSetzen()
        }
        let stand = pb.changeCount
        guard stand != letzterStand else { return }
        letzterStand = stand
        guard aktiv, stand != eigenerStand else { return }
        neueKopieVerarbeiten()
    }

    private func neueKopieVerarbeiten() {
        let typen = Set((pb.types ?? []).map { $0.rawValue })
        if !typen.isDisjoint(with: Waechter.ueberspringen) { return }
        let vorne = NSWorkspace.shared.frontmostApplication
        if vorne?.processIdentifier == eigenePID { return } // z.B. aus der Zuordnungstabelle kopiert
        if let kennung = vorne?.bundleIdentifier, einstellungen.ausgenommeneApps.contains(kennung) { return }
        guard let text = pb.string(forType: .string), !text.isEmpty else { return }

        let ergebnis = anonymisierer.anonymisieren(text)
        let zeit = Waechter.uhrzeit()
        if ergebnis.geaendert {
            letztesOriginal = text
            schreiben(ergebnis.text)
            mStatus.title = "\(zeit) – ersetzt: \(ergebnis.zusammenfassung)"
            symbolSetzen(zahl: ergebnis.gesamt)
            symbolZuruecksetzenUm = Date().addingTimeInterval(3)
            melden("\(ergebnis.gesamt) Angabe(n) ersetzt", ergebnis.zusammenfassung)
            log("ersetzt: \(ergebnis.zusammenfassung)") // nur Zahlen, keine Inhalte
        } else {
            mStatus.title = "\(zeit) – keine Personendaten gefunden"
        }

        if ergebnis.warnungen.isEmpty {
            warnungSetzen(nil)
        } else {
            let hinweis = ergebnis.warnungen.joined(separator: ", ")
            warnungSetzen("⚠️ Evtl. besonders schützenswert: \(hinweis)")
            if einstellungen.warnungBesondersSchuetzenswert {
                melden("⚠️ Besonders schützenswerte Daten?",
                       "Der Text enthält Hinweise auf: \(hinweis). Bitte vor dem Weitergeben prüfen.",
                       immer: true)
            }
        }
    }

    // MARK: Mit Originalen einfügen (⌃⌥V)

    @objc private func mitOriginalenEinfuegenMenue() {
        mitOriginalenEinfuegen()
    }

    func mitOriginalenEinfuegen() {
        guard let text = pb.string(forType: .string), !text.isEmpty else {
            melden("Nichts einzufügen", "In der Zwischenablage ist kein Text.", immer: true)
            return
        }
        let ergebnis = anonymisierer.zurueckuebersetzen(text)
        guard ergebnis.anzahl > 0 else {
            melden("Keine bekannten Platzhalter",
                   "Der kopierte Text enthält keine Platzhalter, die seit dem Start erfasst wurden.", immer: true)
            return
        }
        schreiben(ergebnis.text, vertraulich: true)
        mStatus.title = "\(Waechter.uhrzeit()) – \(ergebnis.anzahl) Platzhalter mit Originalen eingefügt"
        log("\(ergebnis.anzahl) Platzhalter zurückübersetzt")

        if Einfuegen.bedienungshilfenErlaubt(nachfragen: false) {
            platzhalterText = text
            einfuegenFrist = Date().addingTimeInterval(1.5)
            perform(#selector(einfuegenSobaldLosgelassen), with: nil, afterDelay: 0.02, inModes: [.common])
        } else {
            melden("Originale liegen in der Zwischenablage",
                   "Jetzt ⌘V drücken. Für direktes Einfügen den DSGVO Datenschutz Wächter unter Bedienungshilfen erlauben.",
                   immer: true)
            if !bedienungshilfenGefragt {
                bedienungshilfenGefragt = true
                _ = Einfuegen.bedienungshilfenErlaubt(nachfragen: true)
            }
        }
    }

    /// Wartet, bis ⌃⌥ losgelassen sind, damit die Ziel-App ein sauberes ⌘V erhält
    @objc private func einfuegenSobaldLosgelassen() {
        if Einfuegen.zusatztastenGedrueckt() && Date() < einfuegenFrist {
            perform(#selector(einfuegenSobaldLosgelassen), with: nil, afterDelay: 0.03, inModes: [.common])
            return
        }
        Einfuegen.befehlVSenden()
        if einstellungen.nachEinfuegenWiederherstellen {
            perform(#selector(platzhalterWiederherstellen), with: nil, afterDelay: 1.0, inModes: [.common])
        } else {
            platzhalterText = nil
        }
    }

    /// Nur, wenn seither nichts Neues kopiert wurde
    @objc private func platzhalterWiederherstellen() {
        if let text = platzhalterText, pb.changeCount == eigenerStand {
            schreiben(text)
        }
        platzhalterText = nil
    }

    // MARK: Menü-Aktionen

    @objc private func umschalten() {
        aktiv.toggle()
        mAktiv.state = aktiv ? .on : .off
        symbolSetzen()
        letzterStand = pb.changeCount // während der Pause Kopiertes bleibt unverändert
    }

    @objc private func zurueckuebersetzen() {
        guard let text = pb.string(forType: .string), !text.isEmpty else {
            melden("Nichts zurückzuübersetzen", "In der Zwischenablage ist kein Text.", immer: true)
            return
        }
        let ergebnis = anonymisierer.zurueckuebersetzen(text)
        guard ergebnis.anzahl > 0 else {
            melden("Nichts zurückübersetzt", "Keine bekannten Platzhalter gefunden.", immer: true)
            return
        }
        schreiben(ergebnis.text, vertraulich: true)
        mStatus.title = "\(ergebnis.anzahl) Platzhalter zurückübersetzt"
        melden("\(ergebnis.anzahl) Platzhalter zurückübersetzt", "⌘V fügt jetzt den Text mit Originalen ein.", immer: true)
    }

    @objc private func originalZurueck() {
        guard let original = letztesOriginal else {
            melden("Kein Original", "Es gibt noch kein gespeichertes Original.", immer: true)
            return
        }
        schreiben(original, vertraulich: true)
        mStatus.title = "Original liegt in der Zwischenablage (bis zur nächsten Kopie)"
        melden("Original wiederhergestellt", "⌘V fügt jetzt den unveränderten Text ein.", immer: true)
    }

    @objc private func tabelleZeigen() {
        let zeilen = anonymisierer.zuordnung.tabelle().map { "\($0.platzhalter)  →  \($0.original)" }
        let alert = NSAlert()
        alert.messageText = "Zuordnungstabelle"
        alert.informativeText = "Nur im Arbeitsspeicher – wird beim Beenden gelöscht."
        let rollbereich = NSTextView.scrollableTextView()
        rollbereich.frame = NSRect(x: 0, y: 0, width: 480, height: 280)
        if let textfeld = rollbereich.documentView as? NSTextView {
            textfeld.isEditable = false
            textfeld.isSelectable = true
            textfeld.font = NSFont.monospacedSystemFont(ofSize: 12, weight: .regular)
            textfeld.string = zeilen.isEmpty ? "(noch leer)" : zeilen.joined(separator: "\n")
        }
        alert.accessoryView = rollbereich
        alert.addButton(withTitle: "Schliessen")
        nachVorne()
        alert.runModal()
    }

    @objc private func zuordnungenLoeschen() {
        let alert = NSAlert()
        alert.messageText = "Zuordnungen löschen?"
        alert.informativeText = "Danach können Platzhalter nicht mehr zurückübersetzt werden. Die Nummerierung beginnt neu."
        alert.addButton(withTitle: "Löschen")
        alert.addButton(withTitle: "Abbrechen")
        nachVorne()
        if alert.runModal() == .alertFirstButtonReturn {
            anonymisierer.zuordnungLeeren()
            letztesOriginal = nil
            mStatus.title = "Zuordnungen gelöscht"
        }
    }

    @objc private func mitteilungenUmschalten() {
        einstellungen.benachrichtigungen.toggle()
        mMitteilungen.state = einstellungen.benachrichtigungen ? .on : .off
        do {
            try Einstellungen.speichere(einstellungen.benachrichtigungen, schluessel: "benachrichtigungen", in: Waechter.datei)
        } catch {
            log("Konnte Einstellung nicht speichern: \(error.localizedDescription)")
        }
    }

    @objc private func einstellungenOeffnen() {
        let prozess = Process()
        prozess.executableURL = URL(fileURLWithPath: "/usr/bin/open")
        prozess.arguments = ["-t", Waechter.datei.path]
        try? prozess.run()
    }

    @objc private func einstellungenNeuLaden() {
        einstellungen = einstellungenLaden()
        anonymisierer.setzeEinstellungen(einstellungen)
        anonymisierer.namenserkenner = namenserkenner()
        mMitteilungen.state = einstellungen.benachrichtigungen ? .on : .off
        tastenkuerzelEinrichten()
        melden("Einstellungen geladen", "Die neuen Einstellungen sind aktiv.", immer: true)
    }
}
